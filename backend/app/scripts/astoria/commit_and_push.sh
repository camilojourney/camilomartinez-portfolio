#!/bin/bash
# Script to commit and push generated Astoria map files to git
# This runs after update_progress.py generates new map data

set -e  # Exit on error

echo "📦 Committing updated Astoria map files..."

# Navigate to project root (from /opt/render/project/src/backend/app/scripts/astoria to /opt/render/project/src)
cd /opt/render/project/src

# Verify we're in a git repository
if [ ! -d .git ]; then
    echo "❌ Error: Not in a git repository"
    exit 1
fi

# Ensure we're on main branch (Render may checkout in detached HEAD)
CURRENT_BRANCH=$(git rev-parse --abbrev-ref HEAD)
if [ "$CURRENT_BRANCH" = "HEAD" ]; then
    echo "📍 Detected detached HEAD, switching to main branch..."
    git checkout main
fi

# Configure git for automated commits
git config user.name "Astoria Conquest Bot"
git config user.email "astoria-bot@camilomartinez.co"

# Check if there are changes to commit
if git diff --quiet public/data/astoria-conquest/; then
    echo "✅ No changes to commit - map data is up to date"
    exit 0
fi

# Add the generated files
git add public/data/astoria-conquest/astoria-covered-streets.geojson
git add public/data/astoria-conquest/astoria-progress-stats.json
git add public/data/astoria-conquest/astoria-base-map.geojson

# Create commit with timestamp
TIMESTAMP=$(date -u +"%Y-%m-%d %H:%M:%S UTC")
git commit -m "chore: update Astoria Conquest map data - ${TIMESTAMP}

Automatically generated by Render cron job.
- Updated covered streets
- Updated progress stats
- Refreshed base map"

# Pull latest changes from remote (in case of concurrent runs)
echo "📥 Pulling latest changes from remote..."

# Stash any uncommitted changes (like test_render_workflow.sh)
git stash --include-untracked --quiet || true

# Pull with rebase to maintain linear history
git pull --rebase origin main || {
    echo "⚠️  Rebase had conflicts, auto-resolving..."
    
    # Check if we're in a rebase
    if [ -d .git/rebase-merge ] || [ -d .git/rebase-apply ]; then
        # Resolve conflicts by taking our version (the newer data)
        git checkout --ours public/data/astoria-conquest/astoria-progress-stats.json 2>/dev/null || true
        git checkout --ours public/data/astoria-conquest/astoria-covered-streets.geojson 2>/dev/null || true
        git checkout --ours public/data/astoria-conquest/astoria-base-map.geojson 2>/dev/null || true
        
        # Mark as resolved and continue rebase
        git add public/data/astoria-conquest/*.json public/data/astoria-conquest/*.geojson 2>/dev/null || true
        git rebase --continue 2>/dev/null || {
            # If rebase still fails, abort and try merge
            git rebase --abort 2>/dev/null || true
        }
    fi
    
    # If rebase was aborted or never started, try regular merge
    if [ ! -d .git/rebase-merge ] && [ ! -d .git/rebase-apply ]; then
        git pull --no-rebase --strategy-option=ours origin main || {
            echo "⚠️  Pull failed completely, forcing push..."
            # Last resort: force push (safe because this is automated data)
            git push --force-with-lease origin main
            git stash pop --quiet 2>/dev/null || true
            echo "✅ Force-pushed to GitHub"
            echo "🚀 Vercel will auto-deploy with the new data"
            exit 0
        }
    fi
}

# Restore stashed changes
git stash pop --quiet 2>/dev/null || true

# Push to main branch
echo "📤 Pushing to GitHub..."
git push origin main

echo "✅ Successfully pushed updated map data to GitHub"
echo "🚀 Vercel will auto-deploy with the new data"
